package main

import (
	"bytes"
	"fmt"
	"go/format"
	"log"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"entgo.io/ent/entc"
	"entgo.io/ent/entc/gen"
)

// Generate GORM models from the resolved Ent schema, including mixin fields.
func main() {
	graph, err := entc.LoadGraph("./internal/scheme/entity/entgo", &gen.Config{})
	if err != nil {
		log.Fatal(err)
	}
	for _, node := range graph.Nodes {
		if !strings.HasPrefix(node.Name, "Sys") && !strings.HasPrefix(node.Name, "Org") {
			continue
		}
		var body bytes.Buffer
		imports := map[string]bool{}
		fields := append([]*gen.Field{node.ID}, node.Fields...)
		fmt.Fprintf(&body, "// %s maps the existing %s table.\ntype %s struct {\n", node.Name, node.Table(), node.Name)
		for _, field := range fields {
			typ := field.Type.String()
			if field.Type.Ident != "" {
				typ = field.Type.Ident
			}
			if strings.Contains(typ, "time.") {
				imports["time"] = true
			}
			if strings.Contains(typ, "enumtipe.") {
				imports["github.com/heromicro/omgind/internal/scheme/enumtipe"] = true
			}
			if field.Nillable {
				typ = "*" + typ
			}
			column := field.Column()
			tags := []string{"column:" + field.StorageKey()}
			if field == node.ID {
				tags = append(tags, "primary_key")
				imports["github.com/jinzhu/gorm"] = true
				imports["github.com/heromicro/omgind/pkg/helper/uid/ulid"] = true
			}
			if !column.Nullable {
				tags = append(tags, "not null")
			}
			if column.Size > 0 {
				tags = append(tags, fmt.Sprintf("size:%d", column.Size))
			}
			if column.Default != nil {
				value := fmt.Sprint(column.Default)
				if str, ok := column.Default.(string); ok {
					value = "'" + strings.ReplaceAll(str, "'", "''") + "'"
				}
				tags = append(tags, "default:"+value)
			}
			for _, index := range node.Indexes {
				for _, col := range index.Columns {
					if col == field.StorageKey() {
						kind := "index:"
						if index.Unique {
							kind = "unique_index:"
						}
						tags = append(tags, kind+index.Name)
					}
				}
			}
			jsonTag := field.Name + ",omitempty"
			if field.Sensitive() || strings.Contains(field.StructTag, `json:"-"`) {
				jsonTag = "-"
			}
			fmt.Fprintf(&body, "%s %s `gorm:%q json:%q`\n", field.StructField(), typ, strings.Join(tags, ";"), jsonTag)
		}
		fmt.Fprintln(&body, "}")
		fmt.Fprintf(&body, "\nfunc (%s) TableName() string { return %q }\n", node.Name, node.Table())
		fmt.Fprintf(&body, "\nfunc (m *%s) BeforeCreate(scope *gorm.Scope) error {\n if m.ID == \"\" { return scope.SetColumn(\"ID\", ulid.MustString()) }; return nil\n}\n", node.Name)
		var output bytes.Buffer
		fmt.Fprint(&output, "// Code generated by go run ./cmd/generator/gorm; DO NOT EDIT.\n\npackage entity\n\nimport (\n")
		paths := make([]string, 0, len(imports))
		for path := range imports {
			paths = append(paths, path)
		}
		sort.Strings(paths)
		for _, path := range paths {
			fmt.Fprintf(&output, "%q\n", path)
		}
		fmt.Fprintln(&output, ")")
		output.Write(body.Bytes())
		data, err := format.Source(output.Bytes())
		if err != nil {
			log.Fatalf("%s: %v\n%s", node.Name, err, output.String())
		}
		name := node.Label() + ".entity.go"
		// Match the established schema file names rather than Ent's compact labels.
		for _, entry := range mustReadDir("internal/scheme/entity/entgo") {
			if entry.IsDir() {
				continue
			}
			b, _ := os.ReadFile(filepath.Join("internal/scheme/entity/entgo", entry.Name()))
			if strings.Contains(string(b), "type "+node.Name+" struct") {
				name = entry.Name()
				break
			}
		}
		if err := os.WriteFile(filepath.Join("internal/scheme/entity/gorm", name), data, 0644); err != nil {
			log.Fatal(err)
		}
		fmt.Println("Generated", node.Name)
	}
}

func mustReadDir(path string) []os.DirEntry {
	entries, err := os.ReadDir(path)
	if err != nil {
		log.Fatal(err)
	}
	return entries
}
